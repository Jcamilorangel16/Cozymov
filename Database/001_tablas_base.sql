
CREATE TABLE USUARIO (
    id_usuario VARCHAR(20) PRIMARY KEY,
    primer_nombre VARCHAR(50) NOT NULL,
    segundo_nombre VARCHAR(50) NULL,
    primer_apellido VARCHAR(50) NOT NULL,
    segundo_apellido VARCHAR(50) NULL,
    edad SMALLINT NOT NULL CHECK (edad >= 16),
    correo VARCHAR(150) NOT NULL UNIQUE,
    contrasena VARCHAR(255) NOT NULL,
    rol VARCHAR(20) NOT NULL,
    ocupacion VARCHAR(50) NOT NULL,
    fecha_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);


CREATE TABLE RUTA (
    id_ruta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origen VARCHAR(200) NOT NULL,
    destino VARCHAR(200) NOT NULL,
    lat_origen NUMERIC(9,6) NOT NULL,
    lon_origen NUMERIC(9,6) NOT NULL,
    lat_destino NUMERIC(9,6) NOT NULL,
    lon_destino NUMERIC(9,6) NOT NULL
);