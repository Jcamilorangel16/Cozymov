CREATE TABLE VIAJE (
    id_viaje BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_conductor VARCHAR(20) NOT NULL,
    id_ruta BIGINT NOT NULL,
    fecha_hora_salida TIMESTAMP NOT NULL,
    costo NUMERIC(10,2) NOT NULL CHECK (costo >= 0),
    cupos_disponibles INTEGER NOT NULL CHECK (cupos_disponibles >= 0),
    estado VARCHAR(20) NOT NULL,
    CONSTRAINT fk_viaje_conductor 
        FOREIGN KEY (id_conductor) 
        REFERENCES USUARIO(id_usuario) 
        ON DELETE RESTRICT,
    CONSTRAINT fk_viaje_ruta 
        FOREIGN KEY (id_ruta) 
        REFERENCES RUTA(id_ruta) 
        ON DELETE RESTRICT
);

CREATE TABLE SOLICITUD (
    id_solicitud BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario VARCHAR(20) NOT NULL,
    id_ruta BIGINT NOT NULL,
    fecha_hora TIMESTAMP NOT NULL,
    hora_limite TIME NULL,
    presupuesto NUMERIC(10,2) NULL CHECK (presupuesto >= 0),
    compartir BOOLEAN NOT NULL,
    CONSTRAINT fk_solicitud_usuario 
        FOREIGN KEY (id_usuario) 
        REFERENCES USUARIO(id_usuario) 
        ON DELETE RESTRICT,
    CONSTRAINT fk_solicitud_ruta 
        FOREIGN KEY (id_ruta) 
        REFERENCES RUTA(id_ruta) 
        ON DELETE RESTRICT
);

CREATE TABLE RESERVA (
    id_reserva BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_viaje BIGINT NOT NULL,
    id_pasajero VARCHAR(20) NOT NULL,
    fecha_reserva TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado VARCHAR(20) NOT NULL,
    CONSTRAINT fk_reserva_viaje 
        FOREIGN KEY (id_viaje) 
        REFERENCES VIAJE(id_viaje) 
        ON DELETE RESTRICT,
    CONSTRAINT fk_reserva_pasajero 
        FOREIGN KEY (id_pasajero) 
        REFERENCES USUARIO(id_usuario) 
        ON DELETE RESTRICT
);

CREATE TABLE MENSAJE (
    id_mensaje BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_emisor VARCHAR(20) NOT NULL,
    id_receptor VARCHAR(20) NOT NULL,
    contenido VARCHAR(500) NOT NULL,
    fecha_hora TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    leido BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_mensaje_emisor 
        FOREIGN KEY (id_emisor) 
        REFERENCES USUARIO(id_usuario) 
        ON DELETE RESTRICT,
    CONSTRAINT fk_mensaje_receptor 
        FOREIGN KEY (id_receptor) 
        REFERENCES USUARIO(id_usuario) 
        ON DELETE RESTRICT
);

CREATE TABLE CALIFICACION (
    id_calificacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_reserva BIGINT NOT NULL,
    id_evaluador VARCHAR(20) NOT NULL,
    id_evaluado VARCHAR(20) NOT NULL,
    puntuacion SMALLINT NOT NULL CHECK (puntuacion BETWEEN 1 AND 5),
    comentario VARCHAR(500) NULL,
    CONSTRAINT fk_calificacion_reserva 
        FOREIGN KEY (id_reserva) 
        REFERENCES RESERVA(id_reserva) 
        ON DELETE CASCADE,
    CONSTRAINT fk_calificacion_evaluador 
        FOREIGN KEY (id_evaluador) 
        REFERENCES USUARIO(id_usuario) 
        ON DELETE RESTRICT,
    CONSTRAINT fk_calificacion_evaluado 
        FOREIGN KEY (id_evaluado) 
        REFERENCES USUARIO(id_usuario) 
        ON DELETE RESTRICT
);