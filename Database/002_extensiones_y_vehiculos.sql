CREATE TABLE TELEFONO_USUARIO (
    id_telefono BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario VARCHAR(20) NOT NULL,
    telefono VARCHAR(20) NOT NULL,
    CONSTRAINT fk_telefono_usuario 
        FOREIGN KEY (id_usuario) 
        REFERENCES USUARIO(id_usuario) 
        ON DELETE CASCADE
);

CREATE TABLE PREFERENCIA (
    id_usuario VARCHAR(20) PRIMARY KEY,
    prioridad_costo SMALLINT NULL CHECK (prioridad_costo BETWEEN 1 AND 5),
    prioridad_tiempo SMALLINT NULL CHECK (prioridad_tiempo BETWEEN 1 AND 5),
    preferir_compartir BOOLEAN NULL,
    CONSTRAINT fk_preferencia_usuario 
        FOREIGN KEY (id_usuario) 
        REFERENCES USUARIO(id_usuario) 
        ON DELETE CASCADE
);

CREATE TABLE VEHICULO (
    id_vehiculo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario VARCHAR(20) NOT NULL,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('Automovil', 'Moto','Bicicleta electrica')),
    modelo VARCHAR(50) NOT NULL,
    capacidad SMALLINT NOT NULL CHECK (capacidad > 0),
    ruta_cotidiana VARCHAR(255) NULL,
    foto_vehiculo VARCHAR(255) NULL,
    CONSTRAINT fk_vehiculo_conductor 
        FOREIGN KEY (id_usuario) 
        REFERENCES USUARIO(id_usuario) 
        ON DELETE RESTRICT
);

CREATE TABLE AUTOMOVIL (
    id_vehiculo BIGINT PRIMARY KEY,
    numero_puertas SMALLINT NOT NULL CHECK (numero_puertas IN (2, 3, 4, 5)),
    CONSTRAINT fk_automovil_vehiculo 
        FOREIGN KEY (id_vehiculo) 
        REFERENCES VEHICULO(id_vehiculo) 
        ON DELETE CASCADE
);

CREATE TABLE MOTO (
    id_vehiculo BIGINT PRIMARY KEY,
    modalidad VARCHAR(20) NOT NULL,
    CONSTRAINT fk_moto_vehiculo 
        FOREIGN KEY (id_vehiculo) 
        REFERENCES VEHICULO(id_vehiculo) 
        ON DELETE CASCADE
);

CREATE TABLE BICICLETA_ELECTRICA (
    id_vehiculo BIGINT PRIMARY KEY,
    CONSTRAINT fk_bicicleta_electrica_vehiculo 
        FOREIGN KEY (id_vehiculo) 
        REFERENCES VEHICULO(id_vehiculo) 
        ON DELETE CASCADE
);
